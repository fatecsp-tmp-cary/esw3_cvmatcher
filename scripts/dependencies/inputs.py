"""Render lock inputs from pyproject; --check is offline and never resolves packages."""

import argparse
import hashlib
import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HEADER = "# Generated by scripts/dependencies/inputs.py; edit pyproject.toml instead.\n"


def inputs() -> dict[str, str]:
    project = tomllib.loads((ROOT / "pyproject.toml").read_text())
    return {
        "runtime.in": HEADER + "\n".join(project["project"]["dependencies"]) + "\n",
        "dev.in": HEADER
        + "-r runtime.lock\n"
        + "\n".join(project["dependency-groups"]["dev"])
        + "\n",
        "build.in": HEADER + "\n".join(project["build-system"]["requires"]) + "\n",
        "local-models.in": HEADER
        + "-r runtime.lock\n"
        + "\n".join(project["project"]["optional-dependencies"]["local-models"])
        + "\n",
        "tooling.in": "# Explicit lock-generation tool change only.\npip-tools==7.6.2\n",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--record", action="store_true")
    args = parser.parse_args()
    directory = ROOT / "requirements"
    directory.mkdir(exist_ok=True)
    for name, content in inputs().items():
        path = directory / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f"Stale lock input: {path.relative_to(ROOT)}")
        elif not args.record:
            path.write_text(content)
    manifest_path = directory / "provenance.json"
    hashes = {
        path.name: hashlib.sha256(path.read_bytes()).hexdigest()
        for path in sorted(directory.iterdir())
        if path.suffix in (".in", ".lock")
    }
    if args.record:
        manifest_path.write_text(
            json.dumps(
                {
                    "python": "3.12",
                    "platform": "Linux x86_64",
                    "resolver": "pip-tools==7.6.2",
                    "files": hashes,
                    "limitations": "Python 3.13/Debian requires separate verification.",
                },
                indent=2,
            )
            + "\n"
        )
    if args.check:
        recorded = json.loads(manifest_path.read_text())
        if recorded["files"] != hashes:
            raise SystemExit("Lock provenance differs; explicitly regenerate and verify locks")
        for name in inputs():
            if not (directory / name.replace(".in", ".lock")).is_file():
                raise SystemExit(f"Missing lock for {name}")
        print("Lock inputs and recorded artifacts agree")


if __name__ == "__main__":
    main()
